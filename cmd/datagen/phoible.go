const (
	phoibleFeaturesURL = "https://raw.githubusercontent.com/phoible/dev/master/raw-data/FEATURES/phoible-segments-features.tsv"
	phoibleDataURL     = "https://raw.githubusercontent.com/phoible/dev/master/data/phoible.csv"
)

type segRow struct {
	sym       string
	val, mask uint64
	freq      int // inventories containing the segment, per 10000
}

// genPhoible writes engine/data/segments.tsv (symbol, feature bits, frequency)
// and engine/data/nfc.tsv (precomposed → decomposed characters, so the engine
// can parse NFC input without pulling in Unicode normalisation tables).
func genPhoible() error {
	featPath, err := fetch("phoible-segments-features.tsv", phoibleFeaturesURL)
	if err != nil {
		return err
	}
	dataPath, err := fetch("phoible.csv", phoibleDataURL)
	if err != nil {
		return err
	}
	freq, nInv, err := phoibleFrequencies(dataPath)
	if err != nil {
		return err
	}
	rows, err := phoibleFeatures(featPath)
	if err != nil {
		return err
	}
	for i := range rows {
		rows[i].freq = freq[rows[i].sym] * 10000 / nInv
	}
	sort.Slice(rows, func(i, j int) bool { return rows[i].sym < rows[j].sym })

	var b strings.Builder
	fmt.Fprintf(&b, "# Derived from PHOIBLE 2.0 (CC BY-SA 3.0); generated by cmd/datagen. Do not edit.\n")
	fmt.Fprintf(&b, "# inventories=%d features=%s\n", nInv, strings.Join(phon.PhoibleNames[:], ","))
	fmt.Fprintf(&b, "# symbol\tval\tmask\tfreq_per_10000\n")
	for _, r := range rows {
		fmt.Fprintf(&b, "%s\t%x\t%x\t%d\n", r.sym, r.val, r.mask, r.freq)
	}
	if err := os.WriteFile(filepath.Join(*outDir, "segments.tsv"), []byte(b.String()), 0o644); err != nil {
		return err
	}

	// NFC aliases: every precomposed rune that appears in the NFC form of a symbol.
	alias := map[rune]string{}
	for _, r := range rows {
		for _, c := range norm.NFC.String(r.sym) {
			if d := norm.NFD.String(string(c)); d != string(c) {
				alias[c] = d
			}
		}
	}
	// Also common precomposed vowels users type even if absent from PHOIBLE's set.
	for _, s := range []string{"ãẽĩõũáéíóúàèìòùâêîôûäëïöüāēīōūăĕĭŏŭȳýỹǎěǐǒǔ"} {
		for _, c := range s {
			alias[c] = norm.NFD.String(string(c))
		}
	}
	keys := make([]rune, 0, len(alias))
	for k := range alias {
		keys = append(keys, k)
	}
	sort.Slice(keys, func(i, j int) bool { return keys[i] < keys[j] })
	b.Reset()
	fmt.Fprintf(&b, "# precomposed\tdecomposed; generated by cmd/datagen. Do not edit.\n")
	for _, k := range keys {
		fmt.Fprintf(&b, "%c\t%s\n", k, alias[k])
	}
	if err := os.WriteFile(filepath.Join(*outDir, "nfc.tsv"), []byte(b.String()), 0o644); err != nil {
		return err
	}
	fmt.Printf("segments.tsv: %d segments from %d inventories\n", len(rows), nInv)
	return genDiacritics(rows)
}

// genDiacritics derives each trailing diacritic's feature delta from pairs
// (base, base+diacritic) that are both in the table, taking the most common
// delta. Output: engine/data/diacritics.tsv (mark, set mask, set val, unset mask, pairs).
func genDiacritics(rows []segRow) error {
	bySym := map[string]segRow{}
	for _, r := range rows {
		bySym[r.sym] = r
	}
	type delta struct{ setMask, setVal, unset uint64 }
	counts := map[string]map[delta]int{}
	for _, r := range rows {
		rs := []rune(r.sym)
		if len(rs) < 2 {
			continue
		}
		mark := string(rs[len(rs)-1])
		base, ok := bySym[string(rs[:len(rs)-1])]
		if !ok || !isDiacritic(rs[len(rs)-1]) {
			continue
		}
		changed := (base.mask ^ r.mask) | ((base.val ^ r.val) & base.mask & r.mask)
		d := delta{setMask: changed & r.mask, setVal: r.val & changed & r.mask, unset: changed &^ r.mask}
		if d == (delta{}) {
			continue
		}
		if counts[mark] == nil {
			counts[mark] = map[delta]int{}
		}
		counts[mark][d]++
	}
	marks := make([]string, 0, len(counts))
	for m := range counts {
		marks = append(marks, m)
	}
	sort.Strings(marks)
	var b strings.Builder
	fmt.Fprintf(&b, "# Derived from PHOIBLE 2.0 (CC BY-SA 3.0); generated by cmd/datagen. Do not edit.\n")
	fmt.Fprintf(&b, "# mark\tset_mask\tset_val\tunset_mask\tpairs\tagreeing\n")
	n := 0
	for _, m := range marks {
		var best delta
		bestN, total := 0, 0
		for d, c := range counts[m] {
			total += c
			if c > bestN || (c == bestN && (d.setMask < best.setMask || (d.setMask == best.setMask && d.setVal < best.setVal))) {
				best, bestN = d, c
			}
		}
		if bestN < 2 {
			continue
		}
		fmt.Fprintf(&b, "%s\t%x\t%x\t%x\t%d\t%d\n", m, best.setMask, best.setVal, best.unset, total, bestN)
		n++
	}
	fmt.Printf("diacritics.tsv: %d marks\n", n)
	return os.WriteFile(filepath.Join(*outDir, "diacritics.tsv"), []byte(b.String()), 0o644)
}

func isDiacritic(r rune) bool {
	return unicode.Is(unicode.Mn, r) || unicode.Is(unicode.Lm, r) || unicode.Is(unicode.Sk, r)
}

func phoibleFeatures(path string) ([]segRow, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	sc := bufio.NewScanner(f)
	sc.Buffer(make([]byte, 1<<20), 1<<20)
	if !sc.Scan() {
		return nil, fmt.Errorf("empty features file")
	}
	header := strings.Split(sc.Text(), "\t")
	col := map[string]int{}
	for i, h := range header {
		col[h] = i
	}
	idx := make([]int, phon.NumFeatures)
	for i, name := range phon.PhoibleNames {
		c, ok := col[name]
		if !ok {
			return nil, fmt.Errorf("missing column %q", name)
		}
		idx[i] = c
	}
	var rows []segRow
	skipped := 0
outer:
	for sc.Scan() {
		cells := strings.Split(sc.Text(), "\t")
		var r segRow
		r.sym = norm.NFD.String(cells[0])
		if strings.HasPrefix(r.sym, "*") { // archiphoneme placeholders
			continue
		}
		for fi, c := range idx {
			switch cells[c] {
			case "+":
				r.val |= 1 << fi
				r.mask |= 1 << fi
			case "-":
				r.mask |= 1 << fi
			case "0":
			default: // contour value such as "-,+": a sequence in our model
				skipped++
				continue outer
			}
		}
		rows = append(rows, r)
	}
	fmt.Printf("skipped %d contour segments\n", skipped)
	return rows, sc.Err()
}

func phoibleFrequencies(path string) (map[string]int, int, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, 0, err
	}
	defer f.Close()
	rd := csv.NewReader(f)
	header, err := rd.Read()
	if err != nil {
		return nil, 0, err
	}
	invCol, phCol := -1, -1
	for i, h := range header {
		switch h {
		case "InventoryID":
			invCol = i
		case "Phoneme":
			phCol = i
		}
	}
	seen := map[[2]string]bool{}
	inv := map[string]bool{}
	freq := map[string]int{}
	for {
		rec, err := rd.Read()
		if err == io.EOF {
			break
		}
		if err != nil {
			return nil, 0, err
		}
		ph := norm.NFD.String(rec[phCol])
		k := [2]string{rec[invCol], ph}
		inv[rec[invCol]] = true
		if !seen[k] {
			seen[k] = true
			freq[ph]++
		}
	}
	return freq, len(inv), nil
}
