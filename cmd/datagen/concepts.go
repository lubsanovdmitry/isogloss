const concepticonBase = "https://raw.githubusercontent.com/concepticon/concepticon-data/master/concepticondata/"

//go:embed concepts_extra.tsv
var conceptsExtra string

//go:embed concepts_meta.tsv
var conceptsMeta string

// The seven items of the 1955 100-list that complete Swadesh-207.
var swadesh207Extra = []string{"BREAST", "CLAW", "FULL", "HORN (ANATOMY)", "KNEE", "MOON", "ROUND"}

type concept struct {
	id                 int
	gloss, role, field string
	category, label    string
	freq, stab         int
	taboo              bool
}

func readTSV(path string) ([]map[string]string, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	r := csv.NewReader(f)
	r.Comma = '\t'
	r.LazyQuotes = true
	r.FieldsPerRecord = -1
	recs, err := r.ReadAll()
	if err != nil {
		return nil, err
	}
	var out []map[string]string
	for _, rec := range recs[1:] {
		m := map[string]string{}
		for i, h := range recs[0] {
			if i < len(rec) {
				m[h] = rec[i]
			}
		}
		out = append(out, m)
	}
	return out, nil
}

func handRows(src string) [][]string {
	var out [][]string
	for _, l := range strings.Split(src, "\n") {
		if l == "" || l[0] == '#' {
			continue
		}
		out = append(out, strings.Split(l, "\t"))
	}
	return out
}

func label(gloss string) string {
	g := strings.ToLower(gloss)
	if i := strings.Index(g, " ("); i >= 0 {
		g = g[:i]
	}
	if i := strings.Index(g, " or "); i >= 0 {
		g = g[:i]
	}
	return strings.ReplaceAll(g, " ", "-")
}

// genConcepts writes engine/data/concepts.tsv and returns the concepts.
func genConcepts() ([]concept, error) {
	cpath, err := fetch("concepticon.tsv", concepticonBase+"concepticon.tsv")
	if err != nil {
		return nil, err
	}
	spath, err := fetch("Swadesh-1952-200.tsv", concepticonBase+"conceptlists/Swadesh-1952-200.tsv")
	if err != nil {
		return nil, err
	}
	master, err := readTSV(cpath)
	if err != nil {
		return nil, err
	}
	byGloss := map[string]map[string]string{}
	for _, r := range master {
		byGloss[r["GLOSS"]] = r
	}
	sw, err := readTSV(spath)
	if err != nil {
		return nil, err
	}
	type entry struct{ gloss, role string }
	var list []entry
	for _, r := range sw {
		list = append(list, entry{r["CONCEPTICON_GLOSS"], "swadesh"})
	}
	for _, g := range swadesh207Extra {
		list = append(list, entry{g, "swadesh"})
	}
	for _, r := range handRows(conceptsExtra) {
		list = append(list, entry{r[0], r[1]})
	}
	meta := map[string][]string{}
	for _, r := range handRows(conceptsMeta) {
		meta[r[0]] = r
	}
	seen := map[string]bool{}
	labels := map[string]string{}
	var out []concept
	var missing []string
	for _, e := range list {
		if seen[e.gloss] {
			continue
		}
		seen[e.gloss] = true
		m, ok := byGloss[e.gloss]
		if !ok {
			missing = append(missing, e.gloss)
			continue
		}
		id, _ := strconv.Atoi(m["ID"])
		c := concept{id: id, gloss: e.gloss, role: e.role, field: m["SEMANTICFIELD"], category: m["ONTOLOGICAL_CATEGORY"], label: label(e.gloss), stab: 3}
		switch e.role {
		case "gram":
			c.freq = 2
		case "culture":
			c.freq, c.stab = 4, 4
		default:
			c.freq = 3
		}
		if mm, ok := meta[e.gloss]; ok {
			c.freq, _ = strconv.Atoi(mm[1])
			c.stab, _ = strconv.Atoi(mm[2])
			c.taboo = mm[3] == "1"
		}
		if other, dup := labels[c.label]; dup {
			c.label = c.label + "-" + strconv.Itoa(c.id)
			_ = other
		}
		labels[c.label] = c.gloss
		out = append(out, c)
	}
	for g := range meta {
		if !seen[g] {
			missing = append(missing, "meta:"+g)
		}
	}
	if len(missing) > 0 {
		sort.Strings(missing)
		return nil, fmt.Errorf("glosses not in Concepticon or not in list: %v", missing)
	}
	sort.Slice(out, func(i, j int) bool { return out[i].id < out[j].id })
	var b strings.Builder
	b.WriteString("# Concepts: Swadesh-207 + grammaticalization sources + cultural items.\n")
	b.WriteString("# IDs and fields from Concepticon (CC BY 4.0); freq/stab/taboo hand-curated. Generated by cmd/datagen.\n")
	b.WriteString("# id\tlabel\tgloss\trole\tfield\tcategory\tfreq\tstab\ttaboo\n")
	for _, c := range out {
		t := 0
		if c.taboo {
			t = 1
		}
		fmt.Fprintf(&b, "%d\t%s\t%s\t%s\t%s\t%s\t%d\t%d\t%d\n", c.id, c.label, c.gloss, c.role, c.field, c.category, c.freq, c.stab, t)
	}
	fmt.Printf("concepts.tsv: %d concepts\n", len(out))
	return out, os.WriteFile(filepath.Join(*outDir, "concepts.tsv"), []byte(b.String()), 0o644)
}
