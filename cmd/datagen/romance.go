package main

import (
	"encoding/csv"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"golang.org/x/text/unicode/norm"
)

const iecorBase = "https://raw.githubusercontent.com/lexibank/iecor/master/cldf/"

// IE-CoR language IDs for the calibration languages.
var romance = map[string]string{"68": "spa", "56": "por", "39": "ita", "25": "fra", "59": "ron"}

func readCSV(path string) ([]map[string]string, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	r := csv.NewReader(f)
	r.FieldsPerRecord = -1
	header, err := r.Read()
	if err != nil {
		return nil, err
	}
	var out []map[string]string
	for {
		rec, err := r.Read()
		if err != nil {
			break
		}
		m := map[string]string{}
		for i, h := range header {
			if i < len(rec) {
				m[h] = rec[i]
			}
		}
		out = append(out, m)
	}
	return out, nil
}

// genRomance writes engine/data/romance.tsv: segmented IPA forms for five
// Romance languages from IE-CoR, keyed by Concepticon ID, for calibrating
// the intelligibility metric. Only the first form per language and concept
// is kept.
func genRomance() error {
	fpath, err := fetch("iecor-forms.csv", iecorBase+"forms.csv")
	if err != nil {
		return err
	}
	ppath, err := fetch("iecor-parameters.csv", iecorBase+"parameters.csv")
	if err != nil {
		return err
	}
	forms, err := readCSV(fpath)
	if err != nil {
		return err
	}
	params, err := readCSV(ppath)
	if err != nil {
		return err
	}
	concepticon := map[string]string{}
	for _, p := range params {
		concepticon[p["ID"]] = p["Concepticon_ID"]
	}
	type row struct{ cid, lang, segs string }
	seen := map[string]bool{}
	var rows []row
	for _, f := range forms {
		lang, ok := romance[f["Language_ID"]]
		cid := concepticon[f["Parameter_ID"]]
		if !ok || cid == "" || strings.TrimSpace(f["Segments"]) == "" {
			continue
		}
		k := cid + "/" + lang
		if seen[k] {
			continue
		}
		seen[k] = true
		rows = append(rows, row{cid, lang, norm.NFD.String(f["Segments"])})
	}
	sort.Slice(rows, func(i, j int) bool {
		if rows[i].cid != rows[j].cid {
			return rows[i].cid < rows[j].cid
		}
		return rows[i].lang < rows[j].lang
	})
	var b strings.Builder
	b.WriteString("# IE-CoR (CC BY 4.0) Romance forms for intelligibility calibration. Generated by cmd/datagen.\n")
	b.WriteString("# concepticon_id\tlang\tsegments (space-separated IPA)\n")
	for _, r := range rows {
		fmt.Fprintf(&b, "%s\t%s\t%s\n", r.cid, r.lang, r.segs)
	}
	fmt.Printf("romance.tsv: %d forms\n", len(rows))
	return os.WriteFile(filepath.Join(*outDir, "romance.tsv"), []byte(b.String()), 0o644)
}
