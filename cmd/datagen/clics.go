package main

import (
	"archive/zip"
	"bufio"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

const clicsURL = "https://github.com/clics/clics3/raw/master/clics3-network.gml.zip"

// minFamilies drops colexifications attested in fewer language families.
const minFamilies = 3

// genCLICS writes engine/data/colex.tsv: CLICS³ colexification edges between
// our concepts, weighted by the number of families attesting them.
func genCLICS(concepts []concept) error {
	path, err := fetch("clics3-network.gml.zip", clicsURL)
	if err != nil {
		return err
	}
	zr, err := zip.OpenReader(path)
	if err != nil {
		return err
	}
	defer zr.Close()
	var gml *zip.File
	for _, f := range zr.File {
		if strings.HasSuffix(f.Name, ".gml") {
			gml = f
		}
	}
	if gml == nil {
		return fmt.Errorf("no .gml in %s", path)
	}
	rc, err := gml.Open()
	if err != nil {
		return err
	}
	defer rc.Close()

	ours := map[int]bool{}
	for _, c := range concepts {
		ours[c.id] = true
	}
	nodeConcept := map[string]int{} // GML node id → Concepticon id
	type edge struct{ a, b, fam, lang int }
	var edges []edge

	sc := bufio.NewScanner(rc)
	sc.Buffer(make([]byte, 1<<20), 64<<20)
	var block string
	attrs := map[string]string{}
	flush := func() {
		switch block {
		case "node":
			id, err := strconv.Atoi(attrs["ID"])
			if err == nil {
				nodeConcept[attrs["id"]] = id
			}
		case "edge":
			a, okA := nodeConcept[attrs["source"]]
			b, okB := nodeConcept[attrs["target"]]
			fam, _ := strconv.Atoi(attrs["FamilyWeight"])
			lang, _ := strconv.Atoi(attrs["LanguageWeight"])
			if okA && okB && ours[a] && ours[b] && fam >= minFamilies {
				if a > b {
					a, b = b, a
				}
				edges = append(edges, edge{a, b, fam, lang})
			}
		}
		block = ""
		attrs = map[string]string{}
	}
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		switch line {
		case "node [":
			block = "node"
			continue
		case "edge [":
			block = "edge"
			continue
		case "]":
			flush()
			continue
		}
		if block == "" {
			continue
		}
		k, v, ok := strings.Cut(line, " ")
		if !ok {
			continue
		}
		switch k {
		case "id", "ID", "source", "target", "FamilyWeight", "LanguageWeight":
			attrs[k] = strings.Trim(v, `"`)
		}
	}
	if err := sc.Err(); err != nil {
		return err
	}
	sort.Slice(edges, func(i, j int) bool {
		if edges[i].a != edges[j].a {
			return edges[i].a < edges[j].a
		}
		return edges[i].b < edges[j].b
	})
	var b strings.Builder
	b.WriteString("# CLICS³ colexifications (CC BY 4.0) between Isogloss concepts, families >= " + strconv.Itoa(minFamilies) + ". Generated by cmd/datagen.\n")
	b.WriteString("# concept_a\tconcept_b\tfamilies\tlanguages\n")
	for _, e := range edges {
		fmt.Fprintf(&b, "%d\t%d\t%d\t%d\n", e.a, e.b, e.fam, e.lang)
	}
	fmt.Printf("colex.tsv: %d edges\n", len(edges))
	return os.WriteFile(filepath.Join(*outDir, "colex.tsv"), []byte(b.String()), 0o644)
}
