package main

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

const walsBase = "https://raw.githubusercontent.com/cldf-datasets/wals/master/cldf/"

// Word-order features used for priors and harmonic correlations.
var walsFeatures = []string{"81A", "82A", "83A", "85A", "86A", "87A", "88A", "90A"}

// genWALS writes engine/data/wals.tsv: value counts per feature and joint
// counts for every feature pair, over languages coded for both.
func genWALS() error {
	vpath, err := fetch("wals-values.csv", walsBase+"values.csv")
	if err != nil {
		return err
	}
	cpath, err := fetch("wals-codes.csv", walsBase+"codes.csv")
	if err != nil {
		return err
	}
	values, err := readCSV(vpath)
	if err != nil {
		return err
	}
	codes, err := readCSV(cpath)
	if err != nil {
		return err
	}
	want := map[string]bool{}
	for _, f := range walsFeatures {
		want[f] = true
	}
	codeName := map[string]string{}
	for _, c := range codes {
		codeName[c["ID"]] = c["Name"]
	}
	lang := map[string]map[string]string{} // language → feature → code
	for _, v := range values {
		if !want[v["Parameter_ID"]] {
			continue
		}
		if lang[v["Language_ID"]] == nil {
			lang[v["Language_ID"]] = map[string]string{}
		}
		lang[v["Language_ID"]][v["Parameter_ID"]] = v["Code_ID"]
	}
	single := map[string]int{}
	joint := map[string]int{}
	for _, fs := range lang {
		for _, f := range walsFeatures {
			c, ok := fs[f]
			if !ok {
				continue
			}
			single[c]++
			for _, g := range walsFeatures {
				d, ok := fs[g]
				if ok && f < g {
					joint[c+"\t"+d]++
				}
			}
		}
	}
	var b strings.Builder
	b.WriteString("# WALS Online (CC BY 4.0) word-order value counts and pairwise joint counts. Generated by cmd/datagen.\n")
	b.WriteString("# V\tcode\tname\tcount  |  J\tcode_a\tcode_b\tcount\n")
	keys := make([]string, 0, len(single))
	for k := range single {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		fmt.Fprintf(&b, "V\t%s\t%s\t%d\n", k, codeName[k], single[k])
	}
	keys = keys[:0]
	for k := range joint {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		fmt.Fprintf(&b, "J\t%s\t%d\n", k, joint[k])
	}
	fmt.Printf("wals.tsv: %d values, %d joint cells\n", len(single), len(joint))
	return os.WriteFile(filepath.Join(*outDir, "wals.tsv"), []byte(b.String()), 0o644)
}
